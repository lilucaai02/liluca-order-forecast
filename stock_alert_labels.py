#!/usr/bin/env python3
"""在庫警告の表示文言・色・目安の定数 (シート側と通知側の唯一の出典)。

ダッシュボード２の「在庫警告」列に書き込む文字列と、その背景色 (条件付き書式)、
および「調整の目安」列の目標日数をここ1箇所で定義する。
シート生成側 (dashboard_stock_alert_columns.py) と
通知側 (check_sales_anomaly.py) の両方がここを参照するので、
文言を変えるときはこのファイルだけを直せばよい。

設計意図 (2026-07-31 の変更):
  以前は 🔴🟠🟡 の3色だけで、🔴が「欠品中 / セール停止推奨 / 緊急・発注なし」の
  3種類に使い回されていた。似た丸が並ぶだけで何をすればよいか区別できない、
  という指摘を受けて、アイコンで「何をするか」・背景色で「いつまでに」を
  表すように分けた。
    🏭 = 工場に頼む (自分では解決できない)
    🚚 🔥 = 自分で動かす (手元在庫を送れば解決する)
    🛑 🔽 = 売る量を絞って時間を稼ぐ
  判定条件そのものは変更していない (表示文言と色だけを差し替えた)。
"""

from __future__ import annotations

# --- 在庫警告の表示文言 ----------------------------------------------------
# (表示文字列, 条件付き書式のマッチ文字列, 色キー, 重要度)
# 重要度は数字が小さいほど重い (通知の並び順に使う)。
# マッチ文字列は絵文字を含めない。Sheets の TEXT_CONTAINS は絵文字だと
# 環境によって取りこぼすことがあるため、日本語部分で判定する。
# どの文言も他の文言の部分文字列になっていないこと (誤マッチ防止)。
ALERT_SPECS = (
    ("❌ 欠品中",       "欠品中",       "red",    0),
    ("🏭 すぐ発注",     "すぐ発注",     "red",    1),
    ("🛑 セール全停止", "セール全停止", "red",    2),
    ("🔽 セール減らす", "セール減らす", "orange", 3),
    ("🔥 急いで梱包",   "急いで梱包",   "orange", 4),
    ("🚚 梱包する",     "梱包する",     "yellow", 5),
)

# 個別に参照したいとき用 (数式組み立てで使う)
A_OUT_OF_STOCK = ALERT_SPECS[0][0]   # 在庫日数 <= 0
A_ORDER_NOW = ALERT_SPECS[1][0]      # 手元も発注中もなし
A_SALE_STOP = ALERT_SPECS[2][0]      # 発注中>0 かつ 在庫日数<=15
A_SALE_REDUCE = ALERT_SPECS[3][0]    # 発注中>0
A_PACK_URGENT = ALERT_SPECS[4][0]    # 手元>=梱包必要数 かつ 在庫日数<=15
A_PACK = ALERT_SPECS[5][0]           # 手元>=梱包必要数

ALERT_TEXTS = tuple(s[0] for s in ALERT_SPECS)

# 表示文字列 → 色キー / 重要度
ALERT_COLOR_OF = {s[0]: s[2] for s in ALERT_SPECS}
ALERT_SEVERITY_OF = {s[0]: s[3] for s in ALERT_SPECS}

# 旧文言 (2026-07-31 以前)。条件付き書式の後片付けと、
# シート再計算前の古い値を通知が読んでしまった場合の互換用。
LEGACY_ALERT_TEXTS = (
    "🔴 欠品中", "🔴 緊急・発注なし", "🔴 セール停止推奨",
    "🟠 セール調整検討", "🟠 至急梱包", "🟡 要梱包",
)
LEGACY_MATCH_TEXTS = ("🔴", "🟠", "🟡")

# --- 調整の目安 ------------------------------------------------------------
# 「◯日持たせるには◯個/日」の目標日数。
# 2026-07-31 に 60日 → 14日 に変更 (30日で警告が出る運用なので、
# 警告時点の在庫では60日は物理的に持たず、意味のない数字だった)。
HINT_TARGET_DAYS = 14


def classify_alert(text: str) -> tuple[str, str, int]:
    """在庫警告セルの文字列 → (正規化した表示文字列, 色キー, 重要度)。

    未知の文字列 (旧文言・手入力など) は ("", "", 9) を返す。
    """
    t = (text or "").strip()
    if not t:
        return "", "", 9
    for disp, match, color, sev in ALERT_SPECS:
        if match in t:
            return disp, color, sev
    return t, "", 9
