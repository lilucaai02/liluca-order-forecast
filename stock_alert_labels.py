def classify(text: str, col_key: str) -> tuple[str, str, str, int]:
    """アラートセルの文字列 → (種別キー, 表示例, 色キー, 重要度)。

    空欄・未知の文字列は ("", "", "", 99) を返す。
    数字が埋め込まれた文言 (例「⚠ 未着 25日経過」) にも一致する。
    """
    t = (text or "").strip()
    if not t:
        return "", "", "", 99
    for key, match, exclude, sample, color, sev in specs_for(col_key):
        if match in t and not any(x in t for x in exclude):
            return key, sample, color, sev
    return "", t, "", 99


def is_done(text: str) -> bool:
    """「✓ 済」= 対応済みで有効期間内 (通知から除外する)。"""
    key, *_ = classify(text, "sale")
    return key == K_DONE


def is_overdue(text: str) -> bool:
    """「⚠ 未着」= 対応したはずなのに届いていない (最優先で通知する)。"""
    key, *_ = classify(text, "sale")
    return key == K_OVERDUE


def done_label(done: datetime.date, today: datetime.date) -> str:
    """対応済み日付から「販売調整」列に出る文字列を組み立てる (検算・テスト用)。

    シート側の数式と同じ結果になること。
    """
    elapsed = (today - done).days
    if elapsed <= DONE_VALID_DAYS:
        return f"✓ 済 {done.month}/{done.day}"
    return f"⚠ 未着 {elapsed}日経過"
